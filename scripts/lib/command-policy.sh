#!/usr/bin/env bash
# Parse the shipped policy once before rendering or validating any adapter.
command_policy_load() {
  local file=$1 data
  data=$(LC_ALL=C awk -F '\t' '
    function invalid() { printf "%s:%d: invalid command policy row\n", FILENAME, NR > "/dev/stderr"; failed=1; exit 2 }
    NR==1 { if ($0!="prefix\tdecision\treason") invalid(); next }
    NR>257 || NF!=3 || $2!="deny" || length($1)>200 || length($3)>400 ||
        $1 !~ /^[[:alnum:]_.~\/:*=-]+( [[:alnum:]_.~\/:*=-]+)*$/ ||
        $1 !~ /^[[:alnum:]_.\/-]/ || $3 !~ /^[[:print:]]+$/ || seen[$1]++ { invalid() }
    {print $1}
    END {if (!failed && NR<2) invalid()}
  ' "$file") || return 2
  COMMAND_POLICY_PREFIXES=$(printf '%s\n' "$data" | jq -Rsc 'split("\n")[:-1]') || return 2
}

command_policy_claude() {
  jq -cn --argjson p "$COMMAND_POLICY_PREFIXES" '
    $p | map(if contains("*") then "Bash(" + . + ")" else "Bash(" + . + ":*)" end)'
}

command_policy_opencode() {
  jq -cn --argjson p "$COMMAND_POLICY_PREFIXES" '
    $p | map(if contains("*") then [.] else [., . + " *"] end) | flatten |
    map({action:"shell",resource:.,effect:"deny"})'
}

command_policy_codex() {
  printf '%s\n' '# Generated by scripts/render-command-policy.sh from config/command-policy.tsv.'
  printf '# Policy prefixes: %s\n' "$COMMAND_POLICY_PREFIXES"
  # Stars inside tokens are shell permission globs. Codex only supports literal argv
  # tokens, so it uses the owner-approved surrounding fixed prefixes where possible.
  jq -nr --argjson p "$COMMAND_POLICY_PREFIXES" '
    $p[] | select(contains("*")|not) |
    "prefix_rule(pattern=" + (split(" ")|tojson) + ", decision=\"forbidden\")"'
}

command_policy_profile() { # CLI profile; policy already loaded
  local rules
  case "$1" in
    claude)
      rules=$(command_policy_claude) &&
        jq -e --argjson rules "$rules" '(.permissions.deny // []) as $deny | all($rules[]; . as $rule | $deny | index($rule)!=null)' "$2" >/dev/null ;;
    opencode)
      rules=$(command_policy_opencode) &&
        jq -e --argjson rules "$rules" '(.permissions // []) as $entries | all($rules[]; . as $rule | $entries | index($rule)!=null)' "$2" >/dev/null ;;
    codex) command_policy_codex | cmp -s "$2" - ;;
    *) return 2 ;;
  esac
}
